from __future__ import annotations

from agentic_sdlc import config as config_mod
from agentic_sdlc import text


def rules(findings):
    return sorted({f.rule for f in findings})


def test_tool_trailers_are_attribution():
    samples = [
        "Co-Authored-By: Claude <noreply@anthropic.com>",
        "Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>",
        "Co-Authored-By: Cursor Agent <agent@cursor.com>",
        "Signed-off-by: Claude Code <noreply@anthropic.com>",
        "Assisted-by: ChatGPT",
    ]
    for sample in samples:
        assert rules(text.attribution_findings(f"Fix parser\n\n{sample}\n")) == ["ATTR-1"], sample


def test_human_trailers_pass():
    sample = "Fix parser\n\nCo-Authored-By: Jane Doe <jane@example.com>\nSigned-off-by: Jane Doe <jane@example.com>\n"
    assert text.attribution_findings(sample) == []


def test_generated_footers_and_emoji_are_attribution():
    samples = [
        "\U0001f916 Generated with [Claude Code](https://claude.com/claude-code)",
        "Generated by ChatGPT",
        "Made with Cursor",
        "This patch was written with an AI assistant.",
        "drafted using Gemini",
    ]
    for sample in samples:
        assert rules(text.attribution_findings(sample)) == ["ATTR-1"], sample


def test_vendor_mention_passes_in_pattern_mode_and_fails_in_strict():
    message = "Add Claude Code plugin manifest and hooks"
    assert text.attribution_findings(message) == []
    strict = config_mod.from_dict({"attribution": {"mode": "strict"}})
    assert rules(text.attribution_findings(message, strict)) == ["ATTR-2"]


def test_strict_mode_leaves_ordinary_words_alone():
    strict = config_mod.from_dict({"attribution": {"mode": "strict"}})
    assert (
        text.attribution_findings(
            "Fix cursor position in the editor; amp up the test timeout", strict
        )
        == []
    )


def test_strict_mode_accepts_extra_vendor_names():
    strict = config_mod.from_dict({"attribution": {"mode": "strict", "vendors": ["acme-bot"]}})
    assert rules(text.attribution_findings("Reviewed by Acme-Bot", strict)) == ["ATTR-2"]


def test_secret_patterns():
    hits = {
        "AWS access key id": "aws_key = AKIA" + "ABCDEFGHIJKLMNOP",
        "GitHub token": "token: ghp_" + "a" * 36,
        "GitHub fine-grained token": "github_pat_" + "A" * 30,
        "private key block": "-----BEGIN OPENSSH PRIVATE KEY-----",
        "JSON web token": "eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.SflKxwRJSMeKKF2QT4fwpMeJf36POk6yJVadQssw5c",
        "OpenAI-style key": "sk-ant-" + "a" * 24,
        "Stripe key": "sk_live_" + "A" * 24,
        "secret assignment": "password = 'hunter2hunter2hunter2hunter2'",
    }
    for name, sample in hits.items():
        found = text.secret_findings(sample)
        assert found and found[0].name == name, name
        assert "withheld" in found[0].excerpt


def test_secret_placeholders_and_lookups_pass():
    clean = [
        "api_key = os.environ['API_KEY']",
        'API_KEY: "${{ secrets.API_KEY }}"',
        "password = 'your-password-goes-here-please'",
        "client_secret = '<client-secret-from-vault>'",
        "token = get_token_from_keychain_somewhere()",
    ]
    for line in clean:
        assert text.secret_findings(line) == [], line


def test_added_lines_keeps_only_additions():
    diff = "--- a/x\n+++ b/x\n@@ -1 +1,2 @@\n-old\n+new\n+more\n context\n"
    assert text.added_lines(diff) == "new\nmore"


def test_voice_findings_levels():
    sample = (
        "There are two things to note — that's why we leverage it.\nLet me know if you need more.\n"
    )
    found = text.voice_findings(sample)
    names = {f.name for f in found}
    assert "em dash [fail]" in names
    assert "counting framing [fail]" in names
    assert "that is why [fail]" in names
    assert "banned word [fail]" in names
    assert "closing offer [fail]" in names
    assert all(text.voice_level(f) == "fail" for f in found)


def test_voice_skips_code_blocks():
    sample = "```\nseamless — robust\n```\nPlain sentence.\n"
    assert text.voice_findings(sample) == []
